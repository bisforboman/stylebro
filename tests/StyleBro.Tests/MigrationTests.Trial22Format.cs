    [Fact]
    public void Format_ComparesHowProjectsParseAFile_ByTheSymbolsItTests()
    {
        // Two frameworks of a project compile the same when the symbols its files test evaluate the same (CommunityToolkit:
        // NET9_0_OR_GREATER is defined for net9.0 only, but no file tests it).
        Write("Shared.cs", "class S\n{\n#if NET8_0_OR_GREATER // newer API\n    int x;\n#elif (FOO && !BAR) || BAZ\n#endif\n}\n");
        Write("Plain.cs", "class P { }\n");
        Assert.Equal(["BAR", "BAZ", "FOO", "NET8_0_OR_GREATER"], FormatCommand.TestedSymbols(Path.Combine(root, "Shared.cs")));

        var core = new FormatCommand.CompileView(["CORECLR", "NET8_0_OR_GREATER"], "12.0", "enable", []);
        var other = new FormatCommand.CompileView(["NET8_0_OR_GREATER"], "12.0", "enable", []);
        var plain = Path.Combine(root, "Plain.cs");
        var shared = Path.Combine(root, "Shared.cs");
        Assert.Equal(core.Key([plain]), other.Key([plain]));
        Assert.Equal(core.Key([shared]), other.Key([shared]));
        Assert.NotEqual(core.Key([shared]), (other with { Defines = [] }).Key([shared]));
        Assert.NotEqual(core.Key([plain]), (other with { LangVersion = "preview" }).Key([plain]));

        // b5a: 'latest' alone made a project look different.
        Assert.Equal("14.0", FormatCommand.EffectiveLangVersion("latest", "10.0.402"));
        Assert.Equal("14.0", FormatCommand.EffectiveLangVersion("LatestMajor", "10.0.100"));
        Assert.Equal("12.0", FormatCommand.EffectiveLangVersion("12", "10.0.402"));
        Assert.Equal("preview", FormatCommand.EffectiveLangVersion("preview", "10.0.402"));

        var view = FormatCommand.ReadView("{ \"Properties\": { \"DefineConstants\": \"TRACE;NET\", \"LangVersion\": \"latest\", \"Nullable\": \"Enable\", \"NETCoreSdkVersion\": \"10.0.402\" }, \"Items\": { \"Compile\": [ { \"FullPath\": \"C:\\\\a.cs\" } ] } }")!;
        Assert.True(view.Defines.SetEquals(["TRACE", "NET"]));
        Assert.Equal(("14.0", "enable"), (view.LangVersion, view.Nullable));
        Assert.Equal(["C:\\a.cs"], view.Compile);
        Assert.Null(FormatCommand.ReadView(null));
    }

