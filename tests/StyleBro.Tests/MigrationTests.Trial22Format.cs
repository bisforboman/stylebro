    [Fact]
    public void Format_GivesFilesTheirEndingBack_WhenEndOfLineIsUnset()
    {
        // d4b: '[*] end_of_line = lf' and the block's 'end_of_line = unset' for C#; the whitespace pass wrote CRLF into every
        // line of the LF files of an autocrlf checkout, on every run.
        Write(".editorconfig", "root = true\n[*]\nend_of_line = lf\n[*.cs]\nend_of_line = unset\n[Set/*.cs]\nend_of_line = lf\n");
        Write("Lf.cs", "class A\n{\n}\n");
        Write("Set/Crlf.cs", "class B\r\n{\r\n}\r\n");
        var lf = Path.Combine(root, "Lf.cs");
        var crlf = Path.Combine(root, "Set", "Crlf.cs");
        Assert.Equal([crlf], FormatCommand.EndOfLineSet(root, [lf, crlf]));

        var endings = FormatCommand.LineEndings(root);
        File.WriteAllText(lf, "class A\r\n{\r\n}\r\n");
        File.WriteAllText(crlf, "class B\n{\n}\n");
        FormatCommand.RestoreLineEndings(endings, files => FormatCommand.EndOfLineSet(root, files));
        Assert.Equal("class A\n{\n}\n", File.ReadAllText(lf)); // unset: its own ending back
        Assert.Equal("class B\n{\n}\n", File.ReadAllText(crlf)); // set to lf: converted on purpose

        // Without the settings check, a converted file stays converted (as before).
        File.WriteAllText(lf, "class A\r\n{\r\n}\r\n");
        FormatCommand.RestoreLineEndings(endings);
        Assert.Equal("class A\r\n{\r\n}\r\n", File.ReadAllText(lf));
    }

    [Fact]
    public void Format_RunsAFrameworkOnlyWhereItsCodeCompilesDifferently()
    {
        // CommunityToolkit: no '#if' tests a NET9_0 or NET10_0 symbol, so net8.0, net9.0 and net10.0 compile the same code:
        // 21 runs before, one per framework and part.
        var plan = new List<(string Framework, List<string> Projects)>
        {
            ("net10.0", ["Lib", "Tests"]),
            ("net472", ["Tests"]),
            ("net8.0", ["Lib", "Tests", "Single"]),
            ("net9.0", ["Lib", "Tests"]),
            ("netstandard2.0", ["Lib"]),
        };
        string? Key(string project, string framework) => (project, framework) switch
        {
            ("Tests", "net472") => "netframework|a",
            (_, "netstandard2.0") => "netstandard|a",
            ("Lib", "net10.0") => "net|b", // a file tests NET10_0_OR_GREATER
            ("Tests", "net9.0") => null, // unknown: runs
            _ => "net|a",
        };

        var merged = FormatCommand.MergeFrameworks(plan, Key);
        Assert.Equal(["net10.0", "net472", "net8.0", "net9.0", "netstandard2.0"], merged.Select(m => m.Framework));
        Assert.Equal(["Lib"], merged[0].Projects);
        Assert.Equal(["Lib", "Tests", "Single"], merged[2].Projects);
        Assert.Equal(["Tests"], merged[3].Projects);

        Assert.DoesNotContain(FormatCommand.MergeFrameworks(plan, (_, _) => "same"), m => m.Framework != "net8.0");
        Assert.Equal(plan.Select(p => p.Projects.Count), FormatCommand.MergeFrameworks(plan, (p, f) => f).Select(m => m.Projects.Count));

        var line = FormatCommand.MultiTargetedLine(plan, FormatCommand.MergeFrameworks(plan, (p, f) => f == "net9.0" ? "net8.0" : f));
        Assert.StartsWith("Multi-targeted: one 'dotnet format' run per target framework (net10.0, net472, net8.0, netstandard2.0). net9.0: no run of its own", line, StringComparison.Ordinal);

        Assert.Equal("net", FormatCommand.FrameworkFamily("net8.0"));
        Assert.Equal("net", FormatCommand.FrameworkFamily("netcoreapp3.1"));
        Assert.Equal("net-windows10.0.17763.0", FormatCommand.FrameworkFamily("net8.0-windows10.0.17763.0"));
        Assert.Equal("netframework", FormatCommand.FrameworkFamily("net472"));
        Assert.Equal("netstandard", FormatCommand.FrameworkFamily("netstandard2.1"));
    }

