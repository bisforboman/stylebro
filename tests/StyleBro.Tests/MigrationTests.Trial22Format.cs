    private const string DirectiveString = "namespace Repro;\n\npublic static class C\n{\n    public static string M()\n    {\n#if NOT_DEFINED\n        string result = \"\"\"\n            // <auto-generated/>\n            #pragma warning disable\n            #nullable enable\n            namespace MyApp;\n            \"\"\";\n#else\n        string result = \"x\";\n#endif\n        return result;\n    }\n}\n";

    [Fact]
    public void Format_ProtectsStringLinesAnotherBranchReadsAsDirectives()
    {
        // CommunityToolkit: '#pragma' lines in a raw string inside '#if' were moved to column 0 where the branch is inactive:
        // 19 CS8999 errors where it's compiled.
        Write("src/Gen/C.cs", DirectiveString);
        Write("src/Gen/Verbatim.cs", DirectiveString.Replace("\"\"\"\n            // <auto-generated/>", "@\"\n            // <auto-generated/>", StringComparison.Ordinal).Replace("            \"\"\";", "            \";", StringComparison.Ordinal));

        // The other branch's string isn't involved, nor a string whose lines start with '#' where every build compiles it.
        Write("src/Gen/Active.cs", "class A\n{\n#if DEBUG\n#pragma warning disable CS0169\n    int x;\n#endif\n    string s = \"\"\"\n        #pragma warning disable\n        \"\"\";\n}\n");
        Write("src/Gen/NoIf.cs", "class B\n{\n    string s = \"\"\"\n        #nullable enable\n        \"\"\";\n}\n");
        Write("src/Gen/Plain.cs", "class D\n{\n#if DEBUG\n    string s = \"\"\"\n        no directive here\n        \"\"\";\n#endif\n}\n");

        Assert.Equal([DirectiveString.IndexOf("#pragma", StringComparison.Ordinal), DirectiveString.IndexOf("#nullable", StringComparison.Ordinal)], FormatCommand.DirectiveStringOffsets(DirectiveString));
        Assert.Empty(FormatCommand.DirectiveStringOffsets(File.ReadAllText(Path.Combine(root, "src", "Gen", "Active.cs"))));
        Assert.Equal(["src/Gen/C.cs", "src/Gen/Verbatim.cs"], FormatCommand.DirectiveStringFiles(root));
        Assert.StartsWith("Protected: src/Gen/C.cs, src/Gen/Verbatim.cs: a multi-line string there", FormatCommand.DirectiveStringLine(["src/Gen/C.cs", "src/Gen/Verbatim.cs"]), StringComparison.Ordinal);

        // While 'dotnet format' runs, those lines' '#' is another character; afterwards the file is as it was, BOM included.
        var file = Path.Combine(root, "src", "Gen", "C.cs");
        File.WriteAllText(file, DirectiveString, new System.Text.UTF8Encoding(true));
        var before = File.ReadAllBytes(file);
        using (new FormatCommand.DirectiveMask(root, ["src/Gen/C.cs", "src/Gen/Plain.cs"]))
        {
            var masked = File.ReadAllText(file);
            Assert.DoesNotContain("#pragma", masked, StringComparison.Ordinal);
            Assert.DoesNotContain("#nullable", masked, StringComparison.Ordinal);
            Assert.Contains("#if NOT_DEFINED", masked, StringComparison.Ordinal);
            Assert.Empty(FormatCommand.DirectiveStringOffsets(masked));

            // What the formatter changes elsewhere in the file stays.
            File.WriteAllText(file, masked.Replace("return result;", "return result; ", StringComparison.Ordinal), new System.Text.UTF8Encoding(true));
        }

        Assert.Equal(DirectiveString.Replace("return result;", "return result; ", StringComparison.Ordinal), File.ReadAllText(file));
        Assert.Equal(before.Take(3), File.ReadAllBytes(file).Take(3));
    }

    [Fact]
    public void Format_PutsBackWhatAKilledRunSwapped_AndStopsOnASwapWithoutRecord()
    {
        // A 'format' killed while 'dotnet format' ran left private-use characters where '#' was: the next command restores them.
        var records = Path.Combine(root, ".records");
        Write("src/Gen/C.cs", DirectiveString);
        Write("src/Gen/Edited.cs", DirectiveString);
        Write("src/Gen/Moved.cs", DirectiveString);
        var file = Path.Combine(root, "src", "Gen", "C.cs");
        var edited = Path.Combine(root, "src", "Gen", "Edited.cs");
        var moved = Path.Combine(root, "src", "Gen", "Moved.cs");
        using var mask = new FormatCommand.DirectiveMask(root, ["src/Gen/C.cs", "src/Gen/Edited.cs", "src/Gen/Moved.cs"], records);
        var record = Assert.Single(Directory.GetFiles(records));

        // A running format's record is left alone, and so are its files (not damaged).
        var log = new List<string>();
        FormatCommand.DirectiveMask.Recover(log.Add, records);
        Assert.Empty(log);
        Assert.Empty(FormatCommand.DirectiveMask.Damaged(root, records));
        Assert.DoesNotContain("#pragma", File.ReadAllText(file), StringComparison.Ordinal);

        // The process is gone (another one has its id now): restored where the swapped characters are still in place.
        var text = File.ReadAllText(record);
        File.WriteAllText(record, System.Text.RegularExpressions.Regex.Replace(text, "\"Started\":\\d+", "\"Started\":1"));
        var masked = File.ReadAllText(edited);
        var mark = masked[masked.IndexOf("pragma", StringComparison.Ordinal) - 1];
        File.WriteAllText(edited, masked.Replace(mark + "nullable", "nullable", StringComparison.Ordinal));

        // Moved off its line start: the same count, but not where a '#' was.
        var movedText = File.ReadAllText(moved);
        var movedMark = movedText[movedText.IndexOf("nullable", StringComparison.Ordinal) - 1];
        File.WriteAllText(moved, movedText.Replace("            " + movedMark + "nullable", "            x " + movedMark + "nullable", StringComparison.Ordinal));
        FormatCommand.DirectiveMask.Recover(log.Add, records);
        Assert.Equal(DirectiveString, File.ReadAllText(file));
        Assert.Equal(3, log.Count);
        Assert.StartsWith("Restored: " + file, log[0], StringComparison.Ordinal);
        Assert.StartsWith("Not restored: " + edited, log[1], StringComparison.Ordinal);
        Assert.Contains(mark + "pragma", File.ReadAllText(edited), StringComparison.Ordinal);
        Assert.StartsWith("Not restored: " + moved, log[2], StringComparison.Ordinal);
        File.Delete(moved);
        Assert.Empty(Directory.GetFiles(records));

        // Without a record, format and verify stop on such a file.
        Assert.Equal(["src/Gen/Edited.cs"], FormatCommand.DirectiveMask.Damaged(root, records));
        Assert.StartsWith("Stopped: src/Gen/Edited.cs have a line starting with a private-use character", FormatCommand.DamagedLine(["src/Gen/Edited.cs"]), StringComparison.Ordinal);
        Write("A.csproj", "<Project Sdk=\"Microsoft.NET.Sdk\" />\n");
        var lines = new List<string>();
        Assert.Equal(1, FormatCommand.RunPlain([root], lines.Add));
        Assert.Equal(FormatCommand.DamagedLine(["src/Gen/Edited.cs"]), Assert.Single(lines));

        // A private-use character elsewhere (an icon font's glyph in a string) is fine.
        Write("src/Gen/Edited.cs", "class E { string s = \"pragma\"; }\n");
        Assert.Empty(FormatCommand.DirectiveMask.Damaged(root, records));
    }

    [Fact]
    public void Format_IsNotClean_WhenACodeFixFailed()
    {
        // akka: BRO1309's fix threw in every run ("Failed to apply code fix"), and the third run said "0 files changed, clean."
        Write("C.cs", "class C { }\n");
        const string Failure = "  Failed to apply code fix CamelCaseNamingCodeFixProvider for BRO1309: Unexpected value 'UnresolvedAnalyzerReference'";
        int Run(string[] args, Action<string>? output)
        {
            output?.Invoke(Failure);
            return 0;
        }

        var lines = new List<string>();
        Assert.Equal(FormatCommand.NotCleanExitCode, FormatCommand.Run(new[] { root }, lines.Add, Run));
        Assert.Contains("Run 1: 0 files changed, but code fixes failed (below).", lines);
        Assert.StartsWith("Not clean: a code fix failed, so its findings are left: BRO1309 (CamelCaseNamingCodeFixProvider): Unexpected value", lines[^1], StringComparison.Ordinal);
        Assert.DoesNotContain(lines, l => l.Contains("clean.", StringComparison.Ordinal));

        Assert.Equal("BRO1001: Code fix X doesn't support Fix All in Solution.", FormatCommand.FixFailure("Unable to fix BRO1001. Code fix X doesn't support Fix All in Solution."));
        Assert.Null(FormatCommand.FixFailure("Unable to fix CA1822. No associated code fix found.")); // another analyzer's rule without a fix
        Assert.Null(FormatCommand.FixFailure("Formatted code file 'C.cs'."));
    }

    [Fact]
    public void Verify_IsNotClean_WhenTheCopysCodeFixFailed_AndSaysWhatItChecksFirst()
    {
        // akka: the copy's fix threw, so the copy changed nothing, and verify said the findings were ones "no fix changes".
        Write("C.cs", "class C\n{\n}\n");
        var finding = Path.Combine(root, "C.cs") + "(1,7): error BRO1309: Rename 'c' to 'C' [" + Path.Combine(root, "A.csproj") + "]";
        int Run(string[] args, Action<string>? output)
        {
            if (args.Contains("--verify-no-changes"))
            {
                output?.Invoke("Checking StyleBro's rules and the built-in rules bro migrate turns on (1 ids), changing nothing.");
                output?.Invoke("Checked part 1 of 1 (1 of 1)");
                output?.Invoke(finding);
                return FormatCommand.NotCleanExitCode;
            }

            output?.Invoke("Failed to apply code fix CamelCaseNamingCodeFixProvider for BRO1309: boom");
            return 0;
        }

        var lines = new List<string>();
        Assert.Equal(FormatCommand.NotCleanExitCode, FormatCommand.Verify(new[] { "--verify-no-changes" }, root, lines.Add, Run));
        Assert.StartsWith("Checking StyleBro's rules", lines[0], StringComparison.Ordinal); // as it comes, not after the progress
        Assert.StartsWith("Checked part", lines[1], StringComparison.Ordinal);
        Assert.StartsWith("Not clean: a code fix failed", lines[^1], StringComparison.Ordinal);
        Assert.DoesNotContain(lines, l => l.Contains("no fix changes", StringComparison.Ordinal));
    }

    [Fact]
