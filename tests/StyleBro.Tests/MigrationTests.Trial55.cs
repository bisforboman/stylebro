using StyleBro.Analyzers;
using StyleBro.Migrate;

namespace StyleBro.Tests;

/// <summary>What the fifty-fifth trial (ZLinq, Newtonsoft.Json.Schema, FeatureManagement-Dotnet, protobuf-net.Grpc) found in the tool.</summary>
public sealed partial class MigrationTests
{
    [Fact]
    public void Format_OnTheRoot_PutsANewBaselineNextToTheOnlySolutionOneFolderDown_AsThePreviewDoes()
    {
        // Newtonsoft.Json.Schema: its only solution is in Src/. The preview's patch had Src/stylebro.baseline, 'bro format'
        // (on the root) wrote stylebro.baseline, and 'bro format Src/Newtonsoft.Json.Schema.slnx' Src/stylebro.baseline.
        Write("Src/App.slnx", "<Solution>\n  <Project Path=\"App/App.csproj\" />\n</Solution>\n");
        Write("Src/App/App.csproj", "<Project Sdk=\"Microsoft.NET.Sdk\" />\n");
        Write("Src/App/C.cs", "class C\n{\n    private int Count;\n}\n");
        var lines = new List<string>();
        var code = FormatCommand.Run([root], lines.Add, (args, _) =>
        {
            File.AppendAllText(Environment.GetEnvironmentVariable(KeptFinding.Variable)!, new KeptFinding(Path.Combine(root, "Src", "App", "C.cs"), 3, 17, "BRO1303", KeptReason.NameInString, "Rename 'Count' to 'count'") + "\n");
            return 0;
        });

        Assert.Equal(0, code);
        Assert.Contains(lines, l => l.StartsWith("Baseline: Src/stylebro.baseline: added 1 kept finding,", StringComparison.Ordinal));
        Assert.False(File.Exists(Path.Combine(root, "stylebro.baseline")));
        Assert.Single(Analyzers.Baseline.Baseline.Parse(File.ReadAllText(Path.Combine(root, "Src", "stylebro.baseline"))).Entries);
    }

    [Fact]
    public void Preview_ListsAnIndentationNoteOnce_WhenALaterPassNumbersTheChangedText()
    {
        // ZLinq: the preview's first format pass said Sum.cs:21,26,32,142, its second (on the fixed text) Sum.cs:21,26,32-33,36,159,
        // and the summary listed both.
        var first = IfBodies.Line(FormatCommand.IfBodiesHeader, root, new Dictionary<string, (string, List<int>)> { [Path.Combine(root, "src", "Sum.cs")] = (string.Empty, [20, 25, 31, 141]) });
        var second = IfBodies.Line(FormatCommand.IfBodiesHeader, root, new Dictionary<string, (string, List<int>)> { [Path.Combine(root, "src", "Sum.cs")] = (string.Empty, [20, 25, 31, 32, 35, 158]) });
        var other = IfBodies.Line(FormatCommand.IfBodiesHeader, root, new Dictionary<string, (string, List<int>)> { [Path.Combine(root, "src", "Sum.cs")] = (string.Empty, [20]), [Path.Combine(root, "src", "Max.cs")] = (string.Empty, [4]) });
        Assert.Contains("src/Sum.cs:21,26,32,142: ", first, StringComparison.Ordinal);

        var notes = new List<string>();
        Assert.True(PreviewCommand.IsNewNote(notes, first));
        notes.Add(first);
        Assert.False(PreviewCommand.IsNewNote(notes, first));
        Assert.False(PreviewCommand.IsNewNote(notes, second));
        Assert.True(PreviewCommand.IsNewNote(notes, other));
        Assert.False(PreviewCommand.IsNewNote(notes, "Run 2: 0 files changed, clean."));
        Assert.True(PreviewCommand.IsNewNote(notes, FormatCommand.NotBuiltHeader + " Tools/Tools.csproj"));
    }

    [Fact]
    public void Format_AGeneratedFilesName_InsideALongerName_IsntABuildStepThatWritesIt()
    {
        // protobuf-net.Grpc: Generated/Reflection.cs (an '<auto-generated>' header, protogen run by hand) was "generated and
        // checked in: rebuild and commit it", because 'protobuf-net.Grpc.Reflection.csproj' in a ProjectReference contains its name.
        Write("src/Lib/Generated/Reflection.cs", "// <auto-generated>\n// </auto-generated>\nclass R { }\n");
        var file = Path.Combine(root, "src", "Lib", "Generated", "Reflection.cs");

        Assert.False(FormatCommand.IsGenerated(file, "<ProjectReference Include=\"..\\protobuf-net.Grpc.Reflection\\protobuf-net.Grpc.Reflection.csproj\" />"));
        Assert.False(FormatCommand.IsGenerated(file, "<Exec Command=\"protogen --csharp_out=. MyReflection.cs\" />"));
        Assert.False(FormatCommand.IsGenerated(file, "<Exec Command=\"protogen --csharp_out=. Grpc.Reflection.cs\" />"));
        Assert.True(FormatCommand.IsGenerated(file, "<Exec Command=\"protogen --csharp_out=Generated/Reflection.cs reflection.proto\" />"));
        Assert.True(FormatCommand.IsGenerated(file, "protogen reflection.proto -o \"Reflection.cs\""));
    }
}
