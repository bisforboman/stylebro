{
    [Fact]
    public void Summary_CountsARuleTwoConventionsTurnOffOnce()
    {
        // Finbuckle.MultiTenant: BRO1306 is off for non-private fields and for private constants, and the summary said
        // "Turned 13 rules off" with BRO1306 listed twice.
        var lists = new Conventions.SummaryLists();
        lists.TurnedOff.AddRange(new[] { "BRO1303 (private fields)", "BRO1306 (non-private fields)", "BRO1133 (null checks)", "BRO1306 (private constants/static readonly fields)" });
        lists.Unfollowed.Add("BRO1001 (types' members: 3 of 3)");

        var summary = string.Join("\n", Conventions.Summary(lists));

        Assert.Contains("  Turned 3 rules off because your code mixes both forms: BRO1303 (private fields),\n    BRO1306 (non-private fields; private constants/static readonly fields), BRO1133 (null checks).", summary);
        Assert.Contains("  Turned 1 rule off because your code doesn't do what it enforces: BRO1001 (types' members: 3 of 3).", summary);
    }

    [Fact]
    public void Format_ADesignersOutputNextToItsModel_IsntGeneratedByTheBuild()
    {
        // Dapper: benchmarks/.../Linq2Sql/DataClasses.designer.cs comes from Visual Studio's LINQ to SQL designer
        // (DataClasses.dbml); the note said to rebuild and commit it. DataSet (.xsd) and EF6 (.edmx) designers alike.
        foreach (var model in new[] { "DataClasses.dbml", "Orders.xsd", "Shop.edmx" })
        {
            var designer = Path.GetFileNameWithoutExtension(model) + ".designer.cs";
            Write(designer, "// <auto-generated>\n//     This code was generated by a tool.\n// </auto-generated>\npartial class C\n{\n}\n");
            Assert.True(FormatCommand.IsGenerated(Path.Combine(root, designer)));
            Write(model, "<model />\n");
            Assert.False(FormatCommand.IsGenerated(Path.Combine(root, designer)));
        }
    }

    [Theory]
    [InlineData(false)]
    [InlineData(true)]
    public void Format_ALibraryWithoutTheRunsFramework_GetsItsPackagesPropsAndTargetsForTheSameBuild(bool withProps)
    {
        // Dapper: Dapper.Tests.Performance (net472) references Dapper (net461;netstandard2.0;...), whose GlobalPackageReference
        // ReferenceTrimmer has props and targets per framework. In the net472 run NuGet's props saw the environment's net472
        // (no import), the targets the cleared framework (the outer build's): "$(ReferenceTrimmerTasksAssembly)" was empty,
        // Dapper didn't load, nor did the 3 projects that need it. Here a props/targets pair in the library's folder.
        Write("Lib/Directory.Build.props", "<Project>\n  <PropertyGroup Condition=\"'$(TargetFramework)' == ''\"><LibTasks>$(MSBuildThisFileDirectory)tasks.dll</LibTasks></PropertyGroup>\n</Project>\n");
        Write("Lib/Directory.Build.targets", "<Project>\n  <UsingTask TaskName=\"LibTask\" AssemblyFile=\"$(LibTasks)\" Condition=\"'$(TargetFramework)' == ''\" />\n</Project>\n");
        Write("Lib/Lib.csproj", "<Project Sdk=\"Microsoft.NET.Sdk\">\n  <PropertyGroup><TargetFrameworks>netstandard2.0;net8.0</TargetFrameworks></PropertyGroup>\n</Project>\n");
        Write("Lib/Lib.cs", "namespace Lib;\n\npublic class A\n{\n}\n");
        Write("Top/Top.csproj", "<Project Sdk=\"Microsoft.NET.Sdk\">\n  <PropertyGroup><TargetFramework>net10.0</TargetFramework></PropertyGroup>\n  <ItemGroup><ProjectReference Include=\"../Lib/Lib.csproj\" /></ItemGroup>\n</Project>\n");
        Write("Top/Top.cs", "namespace Top;\n\npublic class B : Lib.A\n{\n}\n");
        string Full(string name) => Path.Combine(root, name, name + ".csproj");
        var projects = new Dictionary<string, (string[] Frameworks, string[] References)>(StringComparer.OrdinalIgnoreCase)
        {
            [Full("Lib")] = (new[] { "netstandard2.0", "net8.0" }, Array.Empty<string>()),
            [Full("Top")] = (new[] { "net10.0" }, new[] { Full("Lib") }),
        };
        var keep = FormatCommand.Keep(projects, "net10.0");
        Assert.Equal(new[] { Full("Top") }, keep);
        Write("select.targets", FormatCommand.SelectFrameworkTargets);
        Write("select.props", FormatCommand.SelectFrameworkProps);
        Assert.Equal(Path.Combine(root, "select.props"), FormatCommand.SelectProps(Path.Combine(root, "select.targets")));

        int Dotnet(bool run, params string[] arguments)
        {
            // Output to a file, not a pipe: a build node that outlives the build would keep a pipe open.
            var log = Path.Combine(root, "build.log");
            var start = new ProcessStartInfo("dotnet") { WorkingDirectory = root };
            foreach (var argument in arguments.Append($"-flp:logfile={log};verbosity=minimal").Append("-nodeReuse:false"))
            {
                start.ArgumentList.Add(argument);
            }

            start.Environment["MSBUILDDISABLENODEREUSE"] = "1";
            start.Environment["UseSharedCompilation"] = "false";
            if (run)
            {
                start.Environment["TargetFramework"] = "net10.0";
                start.Environment["BeforeMicrosoftNETSdkTargets"] = Path.Combine(root, "select.targets");
                start.Environment["StyleBroFormatKeep"] = "|" + string.Join("|", keep.Select(p => p.ToUpperInvariant())) + "|";
                if (withProps)
                {
                    start.Environment["CustomBeforeDirectoryBuildProps"] = Path.Combine(root, "select.props");
                }
            }

            using var process = Process.Start(start)!;
            process.WaitForExit();
            Assert.True(process.ExitCode == 0 || (run && !withProps), File.Exists(log) ? File.ReadAllText(log) : "exit code " + process.ExitCode);
            return process.ExitCode;
        }

        Dotnet(false, "restore", "Top/Top.csproj");

        // Without the props the repro fails as Dapper did (MSB4088-like: the task assembly is empty), with them it builds.
        Assert.Equal(withProps, Dotnet(true, "build", "Top/Top.csproj", "--no-restore") == 0);
    }
}
