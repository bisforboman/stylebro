using StyleBro.Migrate;

namespace StyleBro.Tests;

/// <summary>What the thirty-first trial (Ursa.Avalonia, Nerdbank.MessagePack, CliWrap, Hangfire) found in init and migrate.</summary>
public sealed partial class MigrationTests
{
    private const string Gpl = "                    GNU GENERAL PUBLIC LICENSE\n                       Version 3, 29 June 2007\n\n Copyright (C) 2007 Free Software Foundation, Inc. <http://fsf.org/>\n";

    [Fact]
    public void VendoredFolders_NeverTheRoot_AndEveryRootLicenseIsOwn()
    {
        // Hangfire: COPYING (the GPL's text, "Copyright (C) 2007 Free Software Foundation") was read as the root's license, its
        // LICENSE.md (Hangfire OÜ) then made the root folder itself vendored, and init marked the whole repository generated.
        Write("App/App.csproj", "<Project Sdk=\"Microsoft.NET.Sdk\" />\n");
        Write("App/Own.cs", "namespace App;\n\npublic class Own\n{\n}\n");
        Write("Root.cs", "namespace App;\n\npublic class Root\n{\n}\n");
        Write("COPYING", Gpl);
        Write("LICENSE.md", "Copyright © 2013-2026 Hangfire OÜ.\n");
        Assert.Empty(Migration.VendoredFolders(root));

        // A copy of either root license below is still the team's; another holder's is vendored.
        Write("App/Lib/COPYING", Gpl);
        Write("App/Lib/Lib.cs", "namespace App;\n\npublic class Lib\n{\n}\n");
        Write("App/Ext/LICENSE.md", "Copyright © 2020 Hangfire OÜ.\n");
        Write("App/Ext/Ext.cs", "namespace App;\n\npublic class Ext\n{\n}\n");
        Write("App/MiniJson/LICENSE", "MIT License\n\nCopyright (c) 2013 Calvin Rien\n");
        Write("App/MiniJson/Json.cs", "namespace App.MiniJson;\n\npublic class Json\n{\n}\n");
        Assert.Equal(["App/MiniJson"], Migration.VendoredFolders(root));

        // An unreadable root license leaves code with a license of its own undecided, never the root's own code.
        using (new FileStream(Path.Combine(root, "COPYING"), FileMode.Open, FileAccess.ReadWrite, FileShare.None))
        {
            Assert.DoesNotContain(".", Migration.UndecidedLicenseFolders(root, StyleCopSetup.EnumerateFiles(root).ToList()));
        }
    }

    [Fact]
    public void Preview_LeavesAPackagesFolderInsideTheRepositoryOut()
    {
        // Hangfire's nuget.config: 'globalPackagesFolder = %USERPROFILE%/.nuget/TrustedPackages', a folder inside the repository
        // off Windows; the copy's restore filled it and the preview counted 12,576 package files as changed.
        Assert.Null(PreviewCommand.PackagesFolderInside(root));
        if (Environment.GetEnvironmentVariable("NUGET_PACKAGES") is { Length: > 0 })
        {
            return; // it wins over every nuget.config
        }

        Write("nuget.config", "<?xml version=\"1.0\" encoding=\"utf-8\"?>\n<configuration>\n  <config>\n    <add key=\"globalPackagesFolder\" value=\"%USERPROFILE%/.nuget/TrustedPackages\" />\n  </config>\n</configuration>\n");
        var expected = OperatingSystem.IsWindows() ? null : "%USERPROFILE%/.nuget/TrustedPackages";
        Assert.Equal(expected, PreviewCommand.PackagesFolderInside(root));

        Write("nuget.config", "<?xml version=\"1.0\" encoding=\"utf-8\"?>\n<configuration>\n  <config>\n    <add key=\"globalPackagesFolder\" value=\"packages\" />\n  </config>\n</configuration>\n");
        Assert.Equal("packages", PreviewCommand.PackagesFolderInside(root));
        PreviewCommand.MakeRepository(root);
        Assert.EndsWith("/packages/\n", File.ReadAllText(Path.Combine(root, ".git", "info", "exclude")).Replace("\r\n", "\n"), StringComparison.Ordinal);
    }

    [Fact]
    public void ExtractedPackages_AreNotTheRepositorysFiles()
    {
        // Hangfire off Windows: the restore's packages folder inside the repository held Microsoft.NET.Test.Sdk's content
        // files and its LICENSE, and init marked them vendored.
        Write("App/App.csproj", "<Project Sdk=\"Microsoft.NET.Sdk\" />\n");
        Write("App/Own.cs", "namespace App;\n\npublic class Own\n{\n}\n");
        Write("LICENSE", "MIT License\n\nCopyright (c) 2024 Acme Corporation\n");
        Write("pkgs/microsoft.net.test.sdk/17.8.0/microsoft.net.test.sdk.17.8.0.nupkg", "zip");
        Write("pkgs/microsoft.net.test.sdk/17.8.0/LICENSE_MIT.txt", "Copyright (c) Microsoft Corporation\n");
        Write("pkgs/microsoft.net.test.sdk/17.8.0/build/net462/Program.cs", "class AutoGeneratedProgram { }\n");
        Write("packages/Old.Lib.1.0.0/Old.Lib.1.0.0.nupkg", "zip");
        Write("packages/Old.Lib.1.0.0/content/Helper.cs", "class Helper { }\n");

        Assert.Empty(Migration.VendoredFolders(root));
        Assert.DoesNotContain(StyleCopSetup.EnumerateFiles(root), f => f.Contains("Program.cs", StringComparison.Ordinal) || f.Contains("Helper.cs", StringComparison.Ordinal));
        Assert.Contains(StyleCopSetup.EnumerateFiles(root), f => f.EndsWith("Own.cs", StringComparison.Ordinal));
    }

    [Fact]
    public void ASkipOfOneFrameworkOfAReference_IsThatFrameworksSkip()
    {
        // Hangfire: the net461 run loaded Hangfire.Core (net451;net46;netstandard1.3;netstandard2.0) as a reference with all its
        // frameworks, and 'Hangfire.Core(netstandard1.3)' was reported as a project no run loaded.
        Assert.Equal(("Hangfire.Core", "netstandard1.3"), FormatCommand.SkippedFor("Hangfire.Core(netstandard1.3)", "net461"));
        Assert.Equal(("Hangfire.Core", "netstandard1.3"), FormatCommand.SkippedFor("Hangfire.Core", "netstandard1.3"));

        var lines = FormatCommand.Incomplete(
            new Dictionary<string, SortedSet<string>> { ["Hangfire.Core"] = new(["netstandard1.3"]) },
            new Dictionary<string, List<string>> { ["Hangfire.Core"] = ["net451", "net46", "netstandard1.3", "netstandard2.0"] });
        Assert.Single(lines);
        Assert.StartsWith(FormatCommand.PartlyIncompleteMarker, lines[0], StringComparison.Ordinal);
    }
}
