# Trial 54 (Dapper): "DataClasses.designer.cs is generated and checked in: rebuild and commit it" for a LINQ to SQL designer
# file next to its .dbml. A .designer.cs next to a .dbml, .xsd or .edmx (LINQ to SQL, DataSet, EF6) is designer-written: no
# such note, and the build stays clean.
@{
    Description = 'LINQ to SQL, DataSet and EF6 designer files'
    Assert = {
        param($repo, $runs)
        foreach ($run in $runs.Values) {
            foreach ($step in $run.Steps.Values) {
                if ($step -is [string]) { continue }
                if ($step.Text -match 'is generated and checked in') { "$($step.Step) asked to rebuild a designer file: $([regex]::Match($step.Text, '.*is generated and checked in.*').Value.Trim())" }
            }
        }
    }
    Create = {
        param($root)
        New-Project $root 'src/Data/Data.csproj' -Extra @'
  <ItemGroup>
    <None Update="DataClasses.dbml" Generator="MSLinqToSQLGenerator" LastGenOutput="DataClasses.designer.cs" />
    <Compile Update="DataClasses.designer.cs" DesignTime="True" AutoGen="True" DependentUpon="DataClasses.dbml" />
    <None Update="Orders.xsd" Generator="MSDataSetGenerator" LastGenOutput="Orders.Designer.cs" />
    <Compile Update="Orders.Designer.cs" DesignTime="True" AutoGen="True" DependentUpon="Orders.xsd" />
    <None Update="Model.edmx" Generator="EntityModelCodeGenerator" LastGenOutput="Model.Designer.cs" />
    <Compile Update="Model.Designer.cs" DesignTime="True" AutoGen="True" DependentUpon="Model.edmx" />
  </ItemGroup>
'@
        Set-Text $root 'src/Data/DataClasses.dbml' '<?xml version="1.0" encoding="utf-8"?><Database Name="Fixture" xmlns="http://schemas.microsoft.com/linqtosql/dbml/2007" />'
        Set-Text $root 'src/Data/Orders.xsd' '<?xml version="1.0" encoding="utf-8"?><xs:schema id="Orders" xmlns:xs="http://www.w3.org/2001/XMLSchema" />'
        Set-Text $root 'src/Data/Model.edmx' '<?xml version="1.0" encoding="utf-8"?><edmx:Edmx Version="3.0" xmlns:edmx="http://schemas.microsoft.com/ado/2009/11/edmx" />'
        foreach ($file in 'DataClasses.designer.cs', 'Orders.Designer.cs', 'Model.Designer.cs') {
            $class = $file.Split('.')[0] + 'Designer'
            Set-Text $root "src/Data/$file" @"
//------------------------------------------------------------------------------
// <auto-generated>
//     This code was generated by a tool.
// </auto-generated>
//------------------------------------------------------------------------------

namespace Data
{
    public partial class $class
    {
        static public int Count;
        public string Name = "";
    }
}
"@
        }
        Set-Messy $root 'src/Data/Repository.cs' -Namespace 'Data'
        New-Solution $root 'Fixture.sln' 'src/Data/Data.csproj'
    }
    Tests = $false
}
