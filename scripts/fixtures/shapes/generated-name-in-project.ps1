# Trial 55 (protobuf-net.Grpc): "Generated/Reflection.cs is generated and checked in: rebuild and commit it" for a hand-run
# generator's file, because 'protobuf-net.Grpc.Reflection.csproj' in a ProjectReference contains its name. A build step must
# name the file whole.
@{
    Description = 'a checked-in generated file whose name sits inside a longer project name'
    Assert = {
        param($repo, $runs)
        foreach ($run in $runs.Values) {
            foreach ($step in $run.Steps.Values) {
                if ($step -is [string]) { continue }
                if ($step.Text -match 'Reflection\.cs is generated and checked in') { "$($step.Step) took Generated/Reflection.cs for a build output" }
            }
        }
    }
    Create = {
        param($root)
        New-Project $root 'src/Grpc.Reflection/Grpc.Reflection.csproj'
        Set-Text $root 'src/Grpc.Reflection/Generated/Reflection.cs' @'
// <auto-generated>
//   Generated by a hand-run tool; checked in.
// </auto-generated>
namespace Grpc.Reflection
{
    public partial class ReflectionService
    {
        static public int Count;
    }
}
'@
        Set-Messy $root 'src/Grpc.Reflection/Service.cs' -Namespace 'Grpc.Reflection'
        New-Project $root 'src/App/App.csproj' -References '../Grpc.Reflection/Grpc.Reflection.csproj'
        Set-Messy $root 'src/App/Startup.cs' -Namespace 'App'
        New-Solution $root 'Fixture.sln' 'src/Grpc.Reflection/Grpc.Reflection.csproj', 'src/App/App.csproj'
    }
    Tests = $false
}
